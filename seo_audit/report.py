"""Report writers: Markdown + self-contained HTML + Pages demo page.

No timestamps anywhere in the reports — two runs on the same site are
byte-identical, which the test suite relies on.
"""

from __future__ import annotations

import html as html_lib
from pathlib import Path

from seo_audit.checks import AuditResult, grade

CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;
max-width:900px;margin:0 auto;padding:24px;color:#1a1a1a;line-height:1.55}
h1{font-size:28px}h2{font-size:20px;border-bottom:1px solid #ddd;padding-bottom:4px}
.score{font-size:56px;font-weight:800}
.bar{height:14px;background:#eee;border-radius:7px;overflow:hidden}
.bar>i{display:block;height:100%;background:#2563eb}
table{border-collapse:collapse;width:100%;font-size:14px}
th,td{border:1px solid #ddd;padding:6px 8px;text-align:left}
th{background:#f5f5f5}.pass{color:#15803d;font-weight:700}
.fail{color:#b91c1c;font-weight:700}.part{color:#b45309;font-weight:700}
code{background:#f5f5f5;padding:1px 4px;border-radius:3px}
.muted{color:#666;font-size:13px}
"""


def _score_label(score: float | None) -> tuple[str, str]:
    if score is None:
        return "n/a", "muted"
    if score >= 1.0:
        return "PASS", "pass"
    if score <= 0.0:
        return "FAIL", "fail"
    return f"{score:.0%}", "part"


def write_markdown(result: AuditResult, out_dir: Path) -> Path:
    lines = [
        f"# SEO + GEO Audit — {result.start_url}",
        "",
        f"**Score: {result.total}/100 — {grade(result.total)}**",
        "",
        f"Pages audited: {result.pages_audited} · Pages that failed to load: {result.pages_failed}",
        "",
        "## Scores by category",
        "",
        "| Category | Score |",
        "|---|---:|",
    ]
    for cat, (_, _, pct) in result.categories.items():
        lines.append(f"| {cat} | {pct}/100 |")
    lines += ["", "## All checks", "", "| Check | Category | Result | Detail |",
              "|---|---|---|---|"]
    for c in result.checks:
        label, _ = _score_label(c.score)
        lines.append(f"| {c.check.title} | {c.check.category} | {label} | {c.detail} |")
    lines += ["", "## Top fixes (highest impact first)", ""]
    if not result.fixes:
        lines.append("Nothing to fix — every check passed.")
    for i, fix in enumerate(result.fixes, 1):
        lines.append(f"{i}. **{fix['title']}** ({fix['category']}, impact {fix['impact']}) — "
                     f"{fix['fix']} _{fix['detail']}_")
        if fix["pages"]:
            for p in fix["pages"]:
                lines.append(f"   - {p}")
    lines += ["", "## Pages audited", ""]
    for p in result.crawl.pages:
        lines.append(f"- {p.url} — HTTP {p.status}, {p.size_bytes} bytes")
    if result.crawl.failed_pages:
        lines += ["", "## Pages that failed to load", ""]
        for f in result.crawl.failed_pages:
            lines.append(f"- {f['url']} — {f['error']}")
    if result.crawl.external_status:
        broken = {u: v for u, v in result.crawl.external_status.items()
                  if v[0] is None or v[0] >= 400}
        lines += ["", "## External links", "",
                  f"Checked {len(result.crawl.external_status)} external link(s), "
                  f"{len(broken)} broken."]
        for u, v in sorted(broken.items()):
            lines.append(f"- {u} — {v[1]}")
    lines += ["",
              "_Generated by seo-geo-audit-cli (free, local, no API key). "
              "Scores are computed from a live crawl of the site above._",
              ""]
    path = out_dir / "report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_html(result: AuditResult, out_dir: Path) -> Path:
    rows = []
    for c in result.checks:
        label, cls = _score_label(c.score)
        rows.append(
            f"<tr><td>{html_lib.escape(c.check.title)}</td>"
            f"<td>{html_lib.escape(c.check.category)}</td>"
            f"<td class=\"{cls}\">{label}</td>"
            f"<td>{html_lib.escape(c.detail)}</td></tr>")
    fixes = ""
    if not result.fixes:
        fixes = "<p>Nothing to fix — every check passed.</p>"
    else:
        items = "".join(
            f"<li><b>{html_lib.escape(f['title'])}</b> ({html_lib.escape(f['category'])}, "
            f"impact {f['impact']}) — {html_lib.escape(f['fix'])} "
            f"<span class=\"muted\">{html_lib.escape(f['detail'])}</span></li>"
            for f in result.fixes)
        fixes = f"<ol>{items}</ol>"
    cats = "".join(
        f"<p>{cat}: {pct}/100</p><div class=\"bar\"><i style=\"width:{pct}%\"></i></div>"
        for cat, (_, _, pct) in result.categories.items())
    pages = "".join(
        f"<li>{html_lib.escape(p.url)} — HTTP {p.status}, {p.size_bytes} bytes</li>"
        for p in result.crawl.pages)
    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>SEO + GEO Audit — {html_lib.escape(result.start_url)}</title>
<style>{CSS}</style></head><body>
<h1>SEO + GEO Audit</h1>
<p><code>{html_lib.escape(result.start_url)}</code></p>
<p class="score">{result.total}<span style="font-size:24px">/100</span></p>
<p><b>{html_lib.escape(grade(result.total))}</b> ·
{result.pages_audited} pages audited · {result.pages_failed} failed to load</p>
<h2>Scores by category</h2>{cats}
<h2>All checks</h2>
<table><tr><th>Check</th><th>Category</th><th>Result</th><th>Detail</th></tr>
{''.join(rows)}</table>
<h2>Top fixes (highest impact first)</h2>{fixes}
<h2>Pages audited</h2><ul>{pages}</ul>
<p class="muted">Generated by seo-geo-audit-cli (free, local, no API key).</p>
</body></html>
"""
    path = out_dir / "report.html"
    path.write_text(doc, encoding="utf-8")
    return path


def write_demo_page(result: AuditResult, out_dir: Path) -> Path:
    """A small Pages-ready showcase page for the sample report."""
    top_fixes = "".join(
        f"<li><b>{html_lib.escape(f['title'])}</b> — {html_lib.escape(f['fix'])}</li>"
        for f in result.fixes[:5])
    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>SEO + GEO Audit — sample report</title>
<style>{CSS}</style></head><body>
<h1>SEO + GEO Site Audit CLI — sample report</h1>
<p>This is a real audit of a small test site, generated by the free CLI.
No API key, no account — the whole audit runs on your machine.</p>
<p><code>{html_lib.escape(result.start_url)}</code></p>
<p class="score">{result.total}<span style="font-size:24px">/100</span></p>
<p><b>{html_lib.escape(grade(result.total))}</b></p>
<h2>Scores by category</h2>
{''.join(f"<p>{cat}: {pct}/100</p><div class=\"bar\"><i style=\"width:{pct}%\"></i></div>" for cat, (_, _, pct) in result.categories.items())}
<h2>Top fixes found</h2>
<ol>{top_fixes}</ol>
<p><a href="report.md">Full report (Markdown)</a> ·
<a href="report.html">Full report (HTML)</a></p>
<p class="muted">Run it yourself: <code>python -m seo_audit --url https://example.com --out report/</code></p>
</body></html>
"""
    path = out_dir / "index.html"
    path.write_text(doc, encoding="utf-8")
    return path


def write_all(result: AuditResult, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    return {
        "md": write_markdown(result, out_dir),
        "html": write_html(result, out_dir),
        "demo": write_demo_page(result, out_dir),
    }
